import { Router } from 'express';
import { protect, authorize } from '../middleware/auth.js';
import { stats } from '../controllers/adminController.js';
import { allApplications, updateStatus } from '../controllers/applicationController.js';
import { listMessages, updateMessage, deleteMessage } from '../controllers/contactController.js';
import { listUsers, deleteUser } from '../controllers/userController.js';
import { mine, createInternship, updateInternship, deleteInternship } from '../controllers/internshipController.js';
import asyncHandler from '../middleware/asyncHandler.js';
const router = Router();
router.use(protect, authorize('admin'));
router.get('/stats', asyncHandler(stats));
router.get('/users', asyncHandler(listUsers));
router.delete('/users/:id', asyncHandler(deleteUser));
router.get('/internships', asyncHandler(mine));
router.post('/internships', asyncHandler(createInternship));
router.patch('/internships/:id', asyncHandler(updateInternship));
router.delete('/internships/:id', asyncHandler(deleteInternship));
router.get('/applications', asyncHandler(allApplications));
router.patch('/applications/:id/status', asyncHandler(updateStatus));
router.get('/messages', asyncHandler(listMessages));
router.patch('/messages/:id', asyncHandler(updateMessage));
router.delete('/messages/:id', asyncHandler(deleteMessage));
export default router;
